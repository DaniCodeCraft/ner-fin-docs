"""Проверка _trim_punct на типовых случаях."""
from src.models.predict import _trim_punct

CASES = [
    ('ООО "Ромашка",',      'ООО "Ромашка"'),      # запятая снаружи — убрать, кавычки внутри — сохранить
    ('ПАО "Сатурн".',       'ПАО "Сатурн"'),       # точка снаружи — убрать
    ('100 руб.',            '100 руб.'),           # сокращение — точку оставить
    ('Иванова И.И.',        'Иванова И.И.'),       # инициалы — точку оставить
    ('(1 000 руб.);',       '1 000 руб.'),         # скобки, точка с запятой — убрать
    ('«Ромашка»',           'Ромашка'),            # парные ёлочки — убрать обе
    ('ООО "Ромашка"',       'ООО "Ромашка"'),      # парные прямые кавычки — убрать обе
    ('"Ромашка',            '"Ромашка'),           # непарная — оставить
    ('  ПАО "Сатурн"  ',    'ПАО "Сатурн"'),       # пробелы по краям — убрать
]

ok = True
for src, expected in CASES:
    got = _trim_punct(src)
    marker = "✅" if got == expected else "❌"
    if got != expected:
        ok = False
    print(f"{marker} {src!r:25} → {got!r:25} (ожидалось {expected!r})")

if ok:
    print("\n✅ Все проверки _trim_punct прошли")
else:
    print("\n❌ Есть расхождения")
    raise SystemExit(1)